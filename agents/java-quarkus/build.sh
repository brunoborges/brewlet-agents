#!/usr/bin/env bash
# Builds the agent into $APP_DIR. Called by scripts/workloads/build.sh, which then packages
# $APP_DIR as a Brewlet application artifact (see the "layers" file next to this script).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
: "${APP_DIR:?run this through scripts/workloads/build.sh}"

"$ROOT/scripts/integrations/mvn.sh" -f "$HERE/pom.xml" -DskipTests clean package

# Quarkus' fast-jar is already split: quarkus-run.jar finds its libraries through a manifest
# Class-Path relative to itself, so lib/ can ship as its own layer at /app/lib and everything
# else (the application jar, the generated bytecode, quarkus-run.jar) as the code layer.
FAST_JAR="$HERE/target/quarkus-app"
mkdir -p "$APP_DIR/deps" "$APP_DIR/code"
cp -R "$FAST_JAR/lib/." "$APP_DIR/deps/"
for entry in "$FAST_JAR"/*; do
  [ "$entry" = "$FAST_JAR/lib" ] || cp -R "$entry" "$APP_DIR/code/"
done

# Some POMs pick native jars by the build host's OS; none of those belong in a Linux artifact.
foreign="$(find "$APP_DIR/deps" -type f \( -iname '*osx*' -o -iname '*macos*' -o -iname '*darwin*' -o -iname '*windows*' \))"
if [ -n "$foreign" ]; then
  echo "error: dependencies resolved for the build host, not linux/$ARCH:" >&2
  echo "$foreign" >&2
  exit 1
fi
